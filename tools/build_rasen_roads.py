"""Lay out Imperial Rasen's road network (CK3 1.21 roads).

CK3 1.21 defines every buildable road as a list of neighbouring provinces
(common/roads/road_types). The vanilla roads name Earth's provinces, which crashes the game on
this map (Rasen stops at province 1330), so the mod replaces that folder (replace_path) and this
builder draws Rasen's own network from the finished map:

- a road may only start and end at a trade market, and CK3 1.21 has one market per duchy, at
  the duchy capital's seat (92% of vanilla road ends are duchy seats), so roads join the
  capitals of neighbouring duchies;
- sea roads join any duchy the land roads leave cut off (Nanhou, the Outer West's capital, and
  several others are on islands) to the nearest duchy capital on the main network;
- the Imperial Way: the roads (and sea crossings) that lead from each realm's capital to Azuma
  Honsha are already built (tier 1) when the game starts, as the empire is thousands of years old.

Routes follow the cheapest land path between province centres, with mountains, jungle and
wetland costlier to cross, and stay inside the duchies they join where they can.

The road graphics (splines) are generated by the game: see docs/overhaul.md, "Roads".

Usage: python tools/build_rasen_roads.py [--check]
"""
from __future__ import annotations

import argparse
import heapq
import math

import rasen_map_graph as graph

MOD = graph.MOD
OUTPUT = 'common/roads/road_types/00_rasen_roads.txt'
TERRAIN_COST = {'mountains': 3.0, 'jungle': 2.0, 'wetlands': 2.0, 'desert': 1.6, 'hills': 1.5,
                'taiga': 1.4, 'forest': 1.2, 'drylands': 1.0, 'plains': 1.0, 'farmlands': 0.9}
SEA_STEP_COST = 1.0
MAX_SEA_STEPS = 12
CAPITAL = 'k_azuma'


def step_cost(a: int, b: int) -> float:
    (ax, ay), (bx, by) = graph.centres()[a], graph.centres()[b]
    cost = (TERRAIN_COST.get(graph.terrain_of(a), 1.0) + TERRAIN_COST.get(graph.terrain_of(b), 1.0)) / 2
    return math.hypot(ax - bx, ay - by) * cost


def land_path(start: int, goal: int, allowed: set[int] | None = None) -> list[int] | None:
    """Cheapest path over land provinces (optionally only through `allowed`)."""
    water = graph.water_ids()
    near = graph.neighbours()
    best = {start: 0.0}
    back: dict[int, int] = {}
    queue = [(0.0, start)]
    while queue:
        cost, here = heapq.heappop(queue)
        if here == goal:
            path = [here]
            while path[-1] != start:
                path.append(back[path[-1]])
            return path[::-1]
        if cost > best[here]:
            continue
        for there in near.get(here, ()):
            if there in water or (allowed is not None and there not in allowed):
                continue
            total = cost + step_cost(here, there)
            if total < best.get(there, math.inf):
                best[there] = total
                back[there] = here
                heapq.heappush(queue, (total, there))
    return None


def sea_path(start: int, targets: set[int]) -> list[int] | None:
    """Shortest crossing from a coastal province through sea zones to one of `targets`."""
    water = graph.water_ids() - graph.impassable_seas()
    near = graph.neighbours()
    back: dict[int, int] = {}
    frontier = [s for s in sorted(near.get(start, ())) if s in water]
    for s in frontier:
        back[s] = start
    depth = 0
    while frontier and depth < MAX_SEA_STEPS:
        depth += 1
        landing = sorted(t for s in frontier for t in near.get(s, ()) if t in targets)
        if landing:
            # The landing nearest by sea zones, then by key for a stable choice.
            end = landing[0]
            sea = next(s for s in frontier if end in near.get(s, ()))
            path = [end, sea]
            while path[-1] != start:
                path.append(back[path[-1]])
            return path[::-1]
        following = []
        for s in frontier:
            for n in sorted(near.get(s, ())):
                if n in water and n not in back:
                    back[n] = s
                    following.append(n)
        frontier = following
    return None


def build() -> list[dict]:
    titles = graph.titles()
    counties = graph.counties()
    seat = {key: info['provinces'][0] for key, info in counties.items()}
    duchy_seat = {d: seat[info['capital']] for d, info in titles.items()
                  if info['tier'] == 'd' and info['capital'] in seat}
    duchy_provinces: dict[str, set[int]] = {}
    for key, info in counties.items():
        duchy_provinces.setdefault(info['duchy'], set()).update(info['provinces'])
    province_duchy = {p: d for d, ps in duchy_provinces.items() for p in ps}
    markets = set(duchy_seat.values())
    roads: dict[tuple[int, int], dict] = {}

    def add(path: list[int] | None, sea: bool = False):
        if not path or len(path) < 2:
            return
        pair = (min(path[0], path[-1]), max(path[0], path[-1]))
        if pair not in roads:
            roads[pair] = {'path': path, 'sea': sea, 'tier': 0}

    # Neighbouring duchy capitals, by land.
    near = graph.neighbours()
    duchy_links = set()
    for p, d in province_duchy.items():
        for n in near.get(p, ()):
            other = province_duchy.get(n)
            if other and other != d:
                duchy_links.add((min(d, other), max(d, other)))
    for a, b in sorted(duchy_links):
        if a in duchy_seat and b in duchy_seat:
            add(land_path(duchy_seat[a], duchy_seat[b], duchy_provinces[a] | duchy_provinces[b])
                or land_path(duchy_seat[a], duchy_seat[b]))

    # Sea crossings until every market is on one network.
    coastal = graph.coastal_provinces()

    def networks() -> list[set[int]]:
        links: dict[int, set[int]] = {m: set() for m in markets}
        for a, b in roads:
            links[a].add(b)
            links[b].add(a)
        found, seen = [], set()
        for m in sorted(markets):
            if m in seen:
                continue
            group, stack = {m}, [m]
            seen.add(m)
            while stack:
                for n in links[stack.pop()]:
                    if n not in seen:
                        seen.add(n)
                        group.add(n)
                        stack.append(n)
            found.append(group)
        found.sort(key=lambda g: (-len(g), min(g)))
        return found

    while True:
        parts = networks()
        if len(parts) == 1:
            break
        main, joined = parts[0], False
        for part in parts[1:]:
            # Leave from the part's market nearest the sea, land at the main network's nearest coast,
            # then go on by land to the market there.
            for market in sorted(part):
                ports = sorted((p for p in duchy_provinces[province_duchy[market]] if p in coastal),
                               key=lambda p: (p != market, p))
                if not ports:
                    continue
                port = ports[0]
                landing_targets = {p for p in coastal if any(
                    land_path(p, m, duchy_provinces[province_duchy[m]]) for m in main
                    if p in duchy_provinces[province_duchy[m]])}
                crossing = sea_path(port, landing_targets)
                if not crossing:
                    continue
                landing = crossing[-1]
                target = duchy_seat[province_duchy[landing]]
                inland = land_path(landing, target, duchy_provinces[province_duchy[landing]]) or [landing]
                start = land_path(market, port, duchy_provinces[province_duchy[market]]) or [market]
                path = start[:-1] + crossing + inland[1:]
                if len(set(path)) == len(path):
                    add(path, sea=True)
                    joined = True
                    break
            if joined:
                break
        if not joined:
            raise SystemExit('Could not join every market: ' + ', '.join(str(sorted(p)) for p in parts[1:]))

    # The Imperial Way: roads from each realm's capital to Azuma Honsha start at tier 1.
    hub = seat[titles[CAPITAL]['capital']]
    links: dict[int, list[tuple[float, int, tuple[int, int]]]] = {}
    for pair, road in roads.items():
        cost = sum(step_cost(x, y) for x, y in zip(road['path'], road['path'][1:]))
        links.setdefault(pair[0], []).append((cost, pair[1], pair))
        links.setdefault(pair[1], []).append((cost, pair[0], pair))
    for kingdom, info in sorted(titles.items()):
        if info['tier'] != 'k' or kingdom == CAPITAL or info['capital'] not in seat:
            continue
        start = seat[info['capital']]
        best, back, queue = {start: 0.0}, {}, [(0.0, start)]
        while queue:
            cost, here = heapq.heappop(queue)
            if here == hub or cost > best[here]:
                continue
            for step, there, pair in links.get(here, ()):
                if cost + step < best.get(there, math.inf):
                    best[there] = cost + step
                    back[there] = (here, pair)
                    heapq.heappush(queue, (cost + step, there))
        here = hub
        while here in back:
            here, pair = back[here]
            roads[pair]['tier'] = 1
    name_of = {seat[k]: k[2:] for k in seat}
    out, used = [], set()
    for pair, road in sorted(roads.items(), key=lambda item: (name_of[item[1]['path'][0]], name_of[item[1]['path'][-1]])):
        first, last = road['path'][0], road['path'][-1]
        key = f"{name_of[first]}_to_{name_of[last]}_{'sea_' if road['sea'] else ''}road"
        while key in used:
            key = key.replace('_road', '_x_road')
        used.add(key)
        out.append({'key': key, **road})
    return out


def render() -> dict[str, bytes]:
    roads = build()
    lines = ['# Generated by tools/build_rasen_roads.py: Imperial Rasen\'s roads (replaces the vanilla roads).', '']
    for road in roads:
        lines.append(f"{road['key']} = {{")
        lines.append(f"\ttier = {road['tier']}")
        if road['sea']:
            lines.append('\tspline_asset_id = 1')
        lines.append('\tprovinces = {')
        lines += [f'\t\t{p}' for p in road['path']]
        lines += ['\t}', '}', '']
    return {OUTPUT: ('﻿' + '\n'.join(lines).rstrip('\n') + '\n').encode('utf-8')}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = render()
    if args.check:
        stale = [r for r, d in files.items() if not (MOD / r).exists() or (MOD / r).read_bytes() != d]
        if stale:
            raise SystemExit('Stale roads: ' + ', '.join(stale))
        print('Roads are current.')
        return
    for relative, data in files.items():
        path = MOD / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    roads = build()
    print(f"Roads: {sum(not r['sea'] for r in roads)} land, {sum(r['sea'] for r in roads)} sea, "
          f"{sum(r['tier'] == 1 for r in roads)} already built.")


if __name__ == '__main__':
    main()
