"""Generate Heavenly Gates and Spirit Fruit Groves for CK3: the aura economy outside Soul Treasures.

From the IF and the Core Rulebook:
- A Heavenly Gate is "when the power of the Heavens reaches down into the mortal world": an
  area's elemental aura surges for a season, and whoever cycles it absorbs its chi. A Gate
  holds a finite amount, so every extra cultivator takes a smaller share; sects send their
  disciples to claim Gates, and rivals ambush them there (a Gate hides them from scanning).
  The first cultivation drains it ("it finished within two hours").
- Rulebook: a Gate has a level of 5 to 15. Cultivating chi uses Athletics or Insight: the
  successes are added to the level, up to triple the level, as Aura Pressure.
- The leylines barely cross in the Outer lands ("a trickle of aura every season"); they are
  stronger in the Inner Kingdoms and strongest on Azuma Honsha.
- The IF's MC awakens Transformations by drawing a whole Gate into their aura; here that is the
  fast, risky way to a Transformation (the slow way is training, tools/build_transformations.py).
- Spirit fruit grows on trees "soaked in ambient chi for generations": eating it raises Aura
  Pressure (+8, +10 in the IF), but less each time ("they can't help as much as they did
  before"). Sects hide Soulfruit Groves; farms and lords serve the fruit to honoured guests.

CK3 mechanics used:
- Gates: a county modifier and variable for a season, opened through the yearly global pulse;
  cultivators travel there with an activity ("Cycle the Heavenly Gate") and may contest it in a
  Clash of Auras. Local AI cultivators claim unclaimed Gates after 45 days.
- Groves: a special building placed at game start (as vanilla's surveys add mines), with a
  yearly harvest to the county holder and a "Share Spirit Fruit" interaction.

Usage: python tools/build_heavenly_gates.py [--check]
"""
