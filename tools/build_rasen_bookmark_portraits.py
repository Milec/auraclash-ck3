"""Give the Trials of the Exalts bookmark's featured characters portraits.

CK3 finds a bookmark character's portrait by name in common/bookmark_portraits. Each of
our six featured rulers reuses the portrait DNA of an All Under Heaven character of the
same gender and a matching look (Japanese for Zenshin and Yokai, Chinese for Cathayan),
read from the installed game and renamed to our key.

Usage: python tools/build_rasen_bookmark_portraits.py [--check] [--game-root <game>]
Needs CK3_GAME_ROOT (or --game-root); without it, prints a notice and does nothing.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

import build_event_overrides as overrides

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'RasenMap/common/bookmark_portraits'
SOURCES = {
    'bm_rasen_bladed': 'bookmark_japan_takenori',         # male, Zenshin
    'bm_rasen_cursed': 'bookmark_japan_morofusa',         # male, Zenshin
    'bm_rasen_azuma': 'bookmark_genpei_takakura_noriko',  # female, Zenshin
    'bm_rasen_wild': 'bookmark_genpei_yoshinaka',         # male, Yokai
    'bm_rasen_mystic': 'bookmark_china_1066_wang_anshi',  # male, Cathayan
    'bm_rasen_sacred': 'bookmark_china_1066_empress_liang',  # female, Cathayan
}


def render(game: Path):
    files = {}
    for key, source in SOURCES.items():
        text = (game / f'common/bookmark_portraits/{source}.txt').read_bytes().decode('utf-8-sig').replace('\r\n', '\n')
        text, count = re.subn(rf'^{source}\s*=\s*\{{', f'{key}={{', text, count=1, flags=re.M)
        if count != 1:
            raise SystemExit(f'{source}: portrait key not found (game version changed?)')
        header = f'# Generated by tools/build_rasen_bookmark_portraits.py: {source} from CK3 1.20.1, renamed.\n'
        files[f'{key}.txt'] = ('﻿' + header + text).encode('utf-8')
    return files


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--game-root', type=Path, default=overrides.DEFAULT_GAME)
    args = parser.parse_args()
    if not (args.game_root / 'common/bookmark_portraits').exists():
        print('CK3 game files not found; skipping (set CK3_GAME_ROOT).')
        return
    files = render(args.game_root)
    if args.check:
        stale = [n for n, d in files.items() if not (OUT / n).exists() or (OUT / n).read_bytes() != d]
        if stale:
            raise SystemExit('Stale bookmark portraits: ' + ', '.join(stale))
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, data in files.items():
            (OUT / name).write_bytes(data)
    print(f'Bookmark portraits: {len(files)} file(s).')


if __name__ == '__main__':
    main()
