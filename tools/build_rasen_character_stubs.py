"""Give the Earth characters that vanilla scripts name a stub on Imperial Rasen.

Vanilla events, decisions and effects name Earth's historical characters directly
(`character:163110`, `character:easteregg_joe_parkin`). Imperial Rasen replaces
history/characters, so each such link logged "Referencing non-existent character" when
the game loaded: about 3,700 error.log lines. As the title stubs do for Earth's realms,
each named character is defined here as a stub who was born and died in year 1, long
before the bookmark. References resolve, triggers about them are false, and no living
character changes.

Usage: python tools/build_rasen_character_stubs.py [--check] [--game-root <game>]
Needs CK3_GAME_ROOT (or --game-root); without it, prints a notice and does nothing.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

import build_event_overrides as overrides

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'AuraClash'
TARGET = 'history/characters/zz_rasen_vanilla_character_stubs.txt'
SCAN = ('common', 'events', 'history', 'gui', 'gfx/portraits')
LINK = re.compile(r'\bcharacter:([A-Za-z0-9_]+)')
DEFINED = re.compile(r'(?m)^([A-Za-z0-9_]+)\s*=\s*\{')
# Every stub shares one of the mod's own cultures and faiths, which always exist.
CULTURE, FAITH = 'zenshin', 'ancestral_rites'


def referenced(game: Path):
    names = set()
    for folder in SCAN:
        for path in (game / folder).rglob('*.txt'):
            if path.relative_to(game).as_posix().startswith('history/characters/'):
                continue
            names.update(LINK.findall(path.read_text(encoding='utf-8-sig', errors='replace')))
    return names


def ours():
    names = set()
    for path in (OUT / 'history/characters').glob('*.txt'):
        if path.name == Path(TARGET).name:
            continue
        names.update(DEFINED.findall(path.read_text(encoding='utf-8-sig')))
    return names


def render(game: Path):
    # Links whose target is a saved scope or a script parameter are not character ids.
    missing = sorted(n for n in referenced(game) - ours() if not n.startswith(('$', 'scope')))
    lines = ['﻿# Generated by tools/build_rasen_character_stubs.py: Earth characters that vanilla scripts name,',
             '# each born and dead in year 1 so the links resolve on Imperial Rasen.']
    for name in missing:
        lines.append(f'{name} = {{ name = "Akio" culture = {CULTURE} religion = {FAITH} 1.1.1 = {{ birth = yes }} 2.1.1 = {{ death = yes }} }}')
    return {TARGET: ('\n'.join(lines) + '\n').encode('utf-8')}, len(missing)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--game-root', type=Path, default=overrides.DEFAULT_GAME)
    args = parser.parse_args()
    if not (args.game_root / 'common').exists():
        print('CK3 game files not found; skipping (set CK3_GAME_ROOT).')
        return
    files, count = render(args.game_root)
    if args.check:
        stale = [r for r, d in files.items() if not (OUT / r).exists() or (OUT / r).read_bytes() != d]
        if stale:
            raise SystemExit('Stale generated files: ' + ', '.join(stale))
    else:
        for relative, data in files.items():
            path = OUT / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f'Character stubs: {count}.')


if __name__ == '__main__':
    main()
