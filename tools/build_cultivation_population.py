"""Rank baselines and independent masters, using the native trait XP caps."""

CORES = ('soul', 'agility', 'power', 'fortitude')
PROFILES = {
    'upper': (tuple(range(30, 51, 5)), (50, 60, 70)),
    'master': (tuple(range(60, 81, 5)), (75, 85, 95)),
    'grandmaster': (tuple(range(85, 101, 5)), (100,)),
}
# A sect's standing follows the natural aura of its region (docs/sects.md), and the strength of
# its ranks follows the author's Aura Pressure figures (one Core dot is 5 XP and 100 AP):
#   Outer Province: Lower Disciple 500, Upper Disciple 1,200, Sect Master 3,500
#   Inner Kingdom:  Lower Disciple 1,500, Upper Disciple 4,000, Sect Master 7,000
# Standing 1 is the Outer figure and 3 the Inner; 2 sits between and 4 (the capital) just above.
STANDING_PROFILES = {
    'lower_t1': ((5, 5, 5, 10), (10, 15, 20)),             # 4-8 dots: about 500 AP
    'lower_t2': ((10, 10, 15), (15, 20, 25)),              # about 1,000 AP
    'lower_t3': ((15, 20), (25, 30, 35)),                  # 12-16 dots: about 1,500 AP
    'lower_t4': ((20, 25), (30, 35, 40)),                  # about 1,800 AP
    'upper_t1': ((10, 15, 20), (30, 40, 50)),              # 8-16 dots: about 1,200 AP
    'upper_t2': ((25, 30, 35), (45, 55, 65)),              # about 2,400 AP
    'upper_t3': ((45, 50, 55), (60, 70, 80)),              # 36-44 dots: about 4,000 AP
    'upper_t4': ((55, 60, 65), (75, 85, 95)),              # about 4,800 AP
    'master_t1': ((40, 45, 50), (60, 70, 80)),             # 32-40 dots: about 3,500 AP
    'master_t2': ((60, 65, 70), (75, 85, 95)),             # about 5,200 AP
    'master_t3': ((85, 90), (85, 95, 100)),                # 68-72 dots: about 7,000 AP
    'master_t4': ((90, 95, 100), (100,)),                  # about 7,600 AP
}
# Aura Pressure beyond what twenty dots in every Core can hold (the Core tracks stop at 8,000).
AP_FLOORS = {'saint': 8000, 'archon': 10000, 'divine_general': 13000, 'exalt': 15000}


def render(identities):
    development = ['''# Generated by tools/build_cultivation_population.py.
# Raise only missing XP. Count is a hard safety bound, never a recurring grant.
ac_ensure_core_floor_effect = {
    while = {
        limit = { NOT = { has_trait_xp = { trait = ac_cultivator track = ac_core_$CORE$ value >= $XP$ } } }
        count = 20
        add_trait_xp = { trait = ac_cultivator track = ac_core_$CORE$ value = 5 }
    }
}
ac_ensure_foundation_floor_effect = {
    while = {
        limit = { NOT = { ac_foundation_xp_trigger = { XP = $XP$ } } }
        count = 20
        ac_gain_foundation_xp_effect = { XP = 5 }
    }
}''']
    for profile, (cores, foundation) in {**PROFILES, **STANDING_PROFILES}.items():
        lines = [f'ac_develop_{profile}_effect = {{',
                 'if = { limit = { ac_has_foundation_trigger = no } ac_random_foundation_effect = yes }']
        for core in CORES:
            lines.append('random_list = {')
            lines += [f'1 = {{ ac_ensure_core_floor_effect = {{ CORE = {core} XP = {xp} }} }}' for xp in cores]
            lines.append('}')
        lines.append('random_list = {')
        lines += [f'1 = {{ ac_ensure_foundation_floor_effect = {{ XP = {xp} }} }}' for xp in foundation]
        lines.append('}')
        if profile.startswith(('master', 'grandmaster')):
            lines.append('add_trait = ac_immortal_core')
        # Recount Aura Pressure and Immortal Cores for the developed rank.
        lines += ['ac_resync_aura_effect = yes', 'ac_update_visual_age_effect = yes', '}']
        development.append('\n'.join(lines))
    development.append('''# Rank changes grant a baseline once; stronger progress is never reduced.
ac_sect_develop_rank_effect = {
    if = {
        limit = { has_trait = ac_cultivator is_alive = yes age >= 16 }
        if = {
            limit = { has_trait = ac_sect_master OR = { NOT = { has_variable = ac_development_rank } var:ac_development_rank < 2 } }
            if = { limit = { var:ac_sect.var:ac_tier ?= 1 } ac_develop_master_t1_effect = yes } else_if = { limit = { var:ac_sect.var:ac_tier ?= 3 } ac_develop_master_t3_effect = yes } else_if = { limit = { var:ac_sect.var:ac_tier ?= 4 } ac_develop_master_t4_effect = yes } else = { ac_develop_master_t2_effect = yes }
            set_variable = { name = ac_development_rank value = 2 }
        }
        else_if = {
            limit = { has_trait = ac_sect_upper_disciple OR = { NOT = { has_variable = ac_development_rank } var:ac_development_rank < 1 } }
            if = { limit = { var:ac_sect.var:ac_tier ?= 1 } ac_develop_upper_t1_effect = yes } else_if = { limit = { var:ac_sect.var:ac_tier ?= 3 } ac_develop_upper_t3_effect = yes } else_if = { limit = { var:ac_sect.var:ac_tier ?= 4 } ac_develop_upper_t4_effect = yes } else = { ac_develop_upper_t2_effect = yes }
            set_variable = { name = ac_development_rank value = 1 }
        }
        else_if = {
            limit = { has_trait = ac_sect_lower_disciple NOT = { has_variable = ac_development_rank } }
            if = { limit = { var:ac_sect.var:ac_tier ?= 1 } ac_develop_lower_t1_effect = yes } else_if = { limit = { var:ac_sect.var:ac_tier ?= 3 } ac_develop_lower_t3_effect = yes } else_if = { limit = { var:ac_sect.var:ac_tier ?= 4 } ac_develop_lower_t4_effect = yes } else = { ac_develop_lower_t2_effect = yes }
            set_variable = { name = ac_development_rank value = 0 }
        }
    }
}
# Raise Aura Pressure to at least $AP$ (Saints, Archons, the Divine General and the Exalts stand
# far above what the Core tracks alone express). The extra is unallocated.
ac_aura_floor_effect = {
    if = {
        limit = { has_trait = ac_cultivator }
        ac_init_aura_effect = yes
        if = { limit = { var:ac_aura_pressure < $AP$ } set_variable = { name = ac_aura_pressure value = $AP$ } }
    }
}''')
    paths = ['ac_roaming_choose_path_effect = {', 'ac_random_foundation_effect = yes', 'random_list = {']
    for _, _, one, two, style, _ in identities:
        paths.append(f'1 = {{ add_trait = ac_style_{style} add_trait = ac_element_{one} add_trait = ac_element_{two} }}')
    paths += ['}', '}']
    roaming = '''# Title scope: one living independent master per eligible kingdom of origin.
# Recruiting one does not immediately create another; only death frees its slot.
ac_roaming_spawn_effect = {
    save_scope_as = ac_roaming_origin
    title_capital_county.holder = {
        create_character = {
            gender_female_chance = 50
            age = { 35 70 }
            culture = this.culture
            faith = this.faith
            location = scope:ac_roaming_origin.title_capital_county.title_province
            random_traits = yes
            trait = ac_cultivator
            trait = ac_roaming_master
            trait = historical_character
            save_scope_as = ac_new_roaming_master
        }
    }
    set_variable = { name = ac_roaming_master value = scope:ac_new_roaming_master }
    scope:ac_new_roaming_master = {
        ac_roaming_choose_path_effect = yes
        random_list = {
            60 = { ac_develop_upper_effect = yes set_variable = { name = ac_roaming_grade value = 1 } set_variable = { name = ac_development_rank value = 1 } }
            30 = { ac_develop_master_effect = yes set_variable = { name = ac_roaming_grade value = 2 } set_variable = { name = ac_development_rank value = 2 } }
            10 = { ac_develop_grandmaster_effect = yes set_variable = { name = ac_roaming_grade value = 3 } set_variable = { name = ac_development_rank value = 3 } }
        }
        if = {
            limit = { NOT = { is_in_pool_at = scope:ac_roaming_origin.title_capital_county.title_province } }
            move_to_pool_at = scope:ac_roaming_origin.title_capital_county.title_province
        }
        add_to_global_variable_list = { name = ac_roaming_masters target = this }
    }
}

# Global scope. Native pools handle court visits and recruitment; only free
# pool characters receive a yearly relocation through the vanilla wanderer helper.
ac_roaming_world_maintenance_effect = {
    every_in_global_list = {
        variable = ac_roaming_masters
        limit = { is_alive = no }
        save_scope_as = ac_dead_roaming_master
        remove_list_global_variable = { name = ac_roaming_masters target = scope:ac_dead_roaming_master }
    }
    every_in_global_list = {
        variable = ac_roaming_masters
        limit = { is_alive = yes is_ai = yes is_pool_character = yes is_ruler = no is_imprisoned = no is_travelling = no NOT = { has_variable = ac_sect } NOT = { exists = involved_activity } }
        fallback_move_to_pool_effect = yes
    }
    every_kingdom = {
        limit = { ac_roaming_origin_eligible_trigger = yes }
        if = {
            limit = { NOT = { var:ac_roaming_master ?= { is_alive = yes } } }
            ac_roaming_spawn_effect = yes
        }
    }
}
'''
    return {
        'common/scripted_effects/ac_cultivation_development_effects.txt': '\n'.join(development),
        'common/scripted_effects/ac_roaming_master_effects.txt': '\n'.join(paths) + '\n' + roaming,
    }
