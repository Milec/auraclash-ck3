def render():
    texts = {
        'common/script_values/ac_duel_values.txt': values(),
        'common/scripted_effects/ac_duel_effects.txt': effects() + '\n' + next_effect(),
        'common/character_interactions/ac_duel_interactions.txt': interactions(),
        'events/ac_duel_events.txt': events(),
        'localization/english/ac_duel_l_english.yml': localization(),
    }
    return {k: (BOM + v.rstrip('\n') + '\n').encode('utf-8') for k, v in texts.items()}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = render()
    if args.check:
        stale = [r for r, d in files.items() if not (OUT / r).exists() or (OUT / r).read_bytes() != d]
        if stale:
            raise SystemExit('Stale generated files: ' + ', '.join(stale))
    else:
        for relative, data in files.items():
            path = OUT / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f'Clash of Auras: {len(files)} files, {len(MOVES)} moves.')


if __name__ == '__main__':
    main()
