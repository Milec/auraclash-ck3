"""Generate the Clash of Auras: a turn-based cultivator duel for the base mod (AuraClash/).

Inspired by the turn-based combat of the Princes of Darkness mod, built on the IF's own
fight rules. In Aura Clash each exchange is fought through a Core (Power, Fortitude,
Agility or Soul). A Core can be surged for a bonus, chi blasts cost Chi Points, and
Techniques add "+rank Battle Prowess".

Rules:
- Vitality = 3 + Fortitude rating. The duel ends at 0 Vitality, or after 8 rounds
  (more Vitality wins).
- Each round both fighters pick a move:
  - Power Strike (Power): beats Iron Guard.
  - Iron Guard (Fortitude): beats Chi Blast. Takes 1 less damage, and a winning guard
    restores 1 Vitality instead of striking.
  - Flash Step (Agility): beats Power Strike.
  - Chi Blast (Soul): costs 1 Chi and rolls +1. Beats Flash Step.
- Roll = 2 x Core rating + Prowess / 4 + Techniques of that Core (max 3) + d6
  + 2 if the move counters the foe's + 2 for Aura Pressure suppression (at least
  double the foe's) + the Core's Surge value when surging (spends a charge).
- The higher roll hits for 1, +1 on a margin of 5 or more, +1 when surged. Ties trade nothing.
- The loser is wounded, or killed in a duel to the death; the winner gains prestige.

Writes into AuraClash/:
  common/script_values/ac_duel_values.txt
  common/scripted_effects/ac_duel_effects.txt
  common/character_interactions/ac_duel_interactions.txt
  events/ac_duel_events.txt
  localization/english/ac_duel_l_english.yml

Usage: python tools/build_duels.py [--check]
"""
