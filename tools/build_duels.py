def techniques_by_core():
    out = {core: [] for core in CORES}
    for key, entry in CATALOGUE.items():
        if entry[1] in out:
            out[entry[1]].append(key)
    return out


def values():
    out = ['# Generated by tools/build_duels.py. Character scope unless noted.',
           'ac_duel_max_vitality = { value = 3 add = ac_core_fortitude_rating max = 12 }',
           'ac_duel_prowess_part = { value = prowess divide = 4 floor = yes min = 0 }']
    for core, techs in techniques_by_core().items():
        out.append(f'ac_duel_{core}_techniques = {{')
        out.append('\tvalue = 0')
        out += [f'\tif = {{ limit = {{ has_character_flag = ac_tech_{t} }} add = 1 }}' for t in techs]
        out += [f'\tmax = {TECH_CAP}', '}']
        out.append(f'ac_duel_{core}_base = {{ value = ac_core_{core}_rating multiply = 2 add = ac_duel_prowess_part '
                   f'add = ac_duel_{core}_techniques }}')
    return '\n'.join(out)


def move_is(move, who='this'):
    return f'var:ac_duel_move = flag:{move}' if who == 'this' else f'var:ac_duel_foe = {{ var:ac_duel_move = flag:{move} }}'


