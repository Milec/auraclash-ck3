"""Generate Soul Treasures, following the Aura Clash IF (menu-cultivation-soultreasure).

A Soul Treasure holds the Aura Pressure of the creature it came from. Refining it into an
Advancement Elixir grants 11% of (treasure AP - your AP), clamped to [10 + 3 x Alchemy, 100];
with Alchemy 4+ the elixir ignores Mortal Limits. Alchemy here is the number of Alchemy perks.
Beasts and the fishbone treasure are the IF's; AP values marked "estimate" are not stated in the IF.
Usage: python tools/build_soul_treasures.py [--check]
"""
