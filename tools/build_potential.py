"""Build innate two-axis Potential, its reveal hooks and shared Core prices."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
THRESHOLDS = (12, 23, 34, 45, 56, 67, 78, 89, 100)
BLOCKS = (8, 9, 10, 12, 14, 16, 20, 24, 32)
WEIGHTS = (400, 280, 180, 70, 40, 20, 6, 3, 1)
XP = (.05, .10, .15, .25, .35, .50, .75, 1, 1.5)
PRESTIGE = (.1, .2, .3, .5, .75, 1, 1.5, 2, 3)


def roll(axis):
    return 'random_list = {\n' + '\n'.join(
        f'{weight} = {{ set_variable = {{ name = ac_potential_{axis}_gene value = {level} }} }}'
        for level, weight in enumerate(WEIGHTS, 1)) + '\n}'


def outputs():
    trait = '''# Generated by tools/build_potential.py. Track modifiers accumulate.
ac_potential = {
 genetic = yes good = yes birth = 0 random_creation = 0
 shown_in_ruler_designer = no
 desc = { first_valid = {
 triggered_desc = { trigger = { NOT = { exists = this } } desc = trait_ac_potential_generic_desc }
 desc = trait_ac_potential_desc
 } }
 icon = { first_valid = {
 triggered_desc = { trigger = { NOT = { exists = this } } desc = "ac_potential_mortal.dds" }
'''
    for tier, minimum in [('heavenly', 7), ('earthly', 4)]:
        trait += f'''triggered_desc = {{ trigger = {{ OR = {{ has_trait_xp = {{ trait = ac_potential track = ac_potential_limit value >= {THRESHOLDS[minimum-1]} }} has_trait_xp = {{ trait = ac_potential track = ac_potential_talent value >= {THRESHOLDS[minimum-1]} }} }} }} desc = "ac_potential_{tier}.dds" }}\n'''
    trait += 'desc = "ac_potential_mortal.dds" } }\n tracks = {\n ac_potential_limit = {\n'
    trait += '\n'.join(f'{v} = {{ }}' for v in THRESHOLDS)
    trait += '\n }\n ac_potential_talent = {\n'
    previous_xp = previous_prestige = 0
    for threshold, xp, prestige in zip(THRESHOLDS, XP, PRESTIGE):
        trait += f'{threshold} = {{ monthly_lifestyle_xp_gain_mult = {xp - previous_xp:.2f} monthly_prestige = {prestige - previous_prestige:.2f} }}\n'
        previous_xp, previous_prestige = xp, prestige
    trait += '} } }\n'
    values = '# Generated by tools/build_potential.py. Price is calculated before adding the next dot.\n'
    for key, axis, numbers, fallback in [('ac_core_cost_interval', 'limit', BLOCKS, 8), ('ac_potential_talent_xp_factor', 'talent', [1+x for x in XP], 1)]:
        values += f'{key} = {{ value = {fallback}\n'
        for level in range(9, 0, -1):
            values += f'{"if" if level == 9 else "else_if"} = {{ limit = {{ has_trait = ac_cultivator has_trait_xp = {{ trait = ac_potential track = ac_potential_{axis} value >= {THRESHOLDS[level-1]} }} }} value = {numbers[level-1]} }}\n'
        values += '}\n'
    values += 'ac_core_formation_cost = { value = ac_core_dots divide = ac_core_cost_interval floor = yes add = 1 multiply = 100 }\n'
    effects = '# Generated by tools/build_potential.py. Genes persist independently of visible traits.\n'
    for axis in ('limit', 'talent'):
        gene = f'ac_potential_{axis}_gene'
        effects += f'ac_roll_potential_{axis}_effect = {{ {roll(axis)} }}\n'
        effects += f'''ac_inherit_potential_{axis}_effect = {{
 if = {{ limit = {{ real_mother ?= {{ is_alive = yes }} real_father ?= {{ is_alive = yes }} exists = real_mother exists = real_father }}
 random_list = {{
 35 = {{ set_variable = {{ name = {gene} value = real_mother.var:{gene} }} }}
 35 = {{ set_variable = {{ name = {gene} value = real_father.var:{gene} }} }}
 27 = {{ ac_roll_potential_{axis}_effect = yes }}
 3 = {{ ac_reinforce_potential_{axis}_effect = yes }}
 }} }}
 else_if = {{ limit = {{ exists = real_mother real_mother = {{ is_alive = yes }} }} random_list = {{
 75 = {{ set_variable = {{ name = {gene} value = real_mother.var:{gene} }} }}
 25 = {{ ac_roll_potential_{axis}_effect = yes }} }} }}
 else_if = {{ limit = {{ exists = real_father real_father = {{ is_alive = yes }} }} random_list = {{
 75 = {{ set_variable = {{ name = {gene} value = real_father.var:{gene} }} }}
 25 = {{ ac_roll_potential_{axis}_effect = yes }} }} }}
 else = {{ ac_roll_potential_{axis}_effect = yes }}
}}
# CK3 script-value min sets a lower bound; max caps the result.
ac_reinforce_potential_{axis}_effect = {{
 set_variable = {{ name = {gene} value = {{ value = real_mother.var:{gene} min = real_father.var:{gene} }} }}
 if = {{ limit = {{ real_mother = {{ var:{gene} <= 3 }} real_father = {{ var:{gene} <= 3 }} }}
 change_variable = {{ name = {gene} add = 3 }} }}
 else_if = {{ limit = {{ real_mother = {{ var:{gene} >= 4 var:{gene} <= 6 }} real_father = {{ var:{gene} >= 4 var:{gene} <= 6 }} }}
 change_variable = {{ name = {gene} add = 3 }} }}
 else_if = {{ limit = {{ real_mother = {{ var:{gene} >= 7 }} real_father = {{ var:{gene} >= 7 }} }}
 set_variable = {{ name = {gene} value = {{ value = var:{gene} add = 1 max = 9 }} }} }}
}}
'''
    effects += '''# Seed unknown parent DNA without recursively walking an entire ancestry.
ac_seed_potential_effect = {
 if = { limit = { NOT = { has_variable = ac_potential_limit_gene } } ac_roll_potential_limit_effect = yes }
 if = { limit = { NOT = { has_variable = ac_potential_talent_gene } } ac_roll_potential_talent_effect = yes }
}
ac_initialize_potential_effect = {
 if = { limit = { OR = { NOT = { has_variable = ac_potential_limit_gene } NOT = { has_variable = ac_potential_talent_gene } } }
 if = { limit = { exists = real_mother real_mother = { is_alive = yes } } real_mother = { ac_seed_potential_effect = yes } }
 if = { limit = { exists = real_father real_father = { is_alive = yes } } real_father = { ac_seed_potential_effect = yes } }
 if = { limit = { NOT = { has_variable = ac_potential_limit_gene } } ac_inherit_potential_limit_effect = yes }
 if = { limit = { NOT = { has_variable = ac_potential_talent_gene } } ac_inherit_potential_talent_effect = yes }
 }
}
ac_reveal_potential_effect = {
 if = { limit = { has_trait = ac_cultivator NOT = { has_character_flag = ac_revealing_potential } }
 add_character_flag = ac_revealing_potential
 ac_initialize_potential_effect = yes
 if = { limit = { NOT = { has_trait = ac_potential } } add_trait = ac_potential }
'''
    for axis in ('limit', 'talent'):
        effects += f'add_trait_xp = {{ trait = ac_potential track = ac_potential_{axis} value = -100 }}\n'
        for level, threshold in enumerate(THRESHOLDS, 1):
            effects += f'if = {{ limit = {{ var:ac_potential_{axis}_gene = {level} }} add_trait_xp = {{ trait = ac_potential track = ac_potential_{axis} value = {threshold} }} }}\n'
    effects += '''remove_character_flag = ac_revealing_potential
 }
}
ac_potential_backfill_effect = {
 if = { limit = { NOT = { has_global_variable = ac_potential_backfilled } }
 set_global_variable = { name = ac_potential_backfilled value = yes }
 every_living_character = { limit = { has_trait = ac_cultivator } ac_reveal_potential_effect = yes }
 }
}
'''
    hooks = '''# Generated by tools/build_potential.py. Native lists append to existing hooks.
on_birth_child = { on_actions = { ac_potential_birth } }
on_character_created = { on_actions = { ac_potential_created } }
on_trait_gained = { on_actions = { ac_potential_trait_gained } }
on_trait_lost = { on_actions = { ac_potential_trait_lost } }
on_game_start_after_lobby = { on_actions = { ac_potential_backfill } }
quarterly_playable_pulse = { on_actions = { ac_potential_backfill } }
ac_potential_backfill = { effect = { ac_potential_backfill_effect = yes } }
ac_potential_birth = { effect = {
 ac_initialize_potential_effect = yes
 if = { limit = { NOT = { has_trait = ac_cultivator } has_trait = ac_potential } remove_trait = ac_potential }
 ac_reveal_potential_effect = yes
} }
ac_potential_created = { trigger = { has_trait = ac_cultivator } effect = { ac_reveal_potential_effect = yes } }
ac_potential_trait_gained = {
 trigger = { OR = { scope:trait = trait:ac_cultivator scope:trait = trait:ac_potential } }
 effect = {
 if = { limit = { has_trait = ac_cultivator } ac_reveal_potential_effect = yes }
 else_if = { limit = { has_trait = ac_potential } remove_trait = ac_potential }
 }
}
ac_potential_trait_lost = {
 trigger = { scope:trait = trait:ac_cultivator has_trait = ac_potential }
 effect = { remove_trait = ac_potential }
}
'''
    loc = '''l_english:
 trait_ac_potential:0 "Potential"
 trait_ac_potential_generic_desc:0 "Innate cultivation potential, revealed upon awakening. Limit delays increases in Core formation cost. Talent grants lifestyle experience and monthly prestige. Each has nine grades, grouped into Mortal, Earthly and Heavenly tiers."
 trait_ac_potential_desc:0 "Innate cultivation capacity, revealed through awakening.\\n\\n#V Limit: [ROOT.GetCharacter.Custom('AC_PotentialLimit')]#! — Core costs increase every [ROOT.GetCharacter.MakeScope.ScriptValue('ac_core_cost_interval')|0] total dots.\\n#V Talent: [ROOT.GetCharacter.Custom('AC_PotentialTalent')]#! — [ROOT.GetCharacter.Custom('AC_PotentialTalentBonus')].\\n\\nEach aptitude is inherited separately. Rare reinforcement can raise a child into the next tier. The icon reflects the higher tier of the two aptitudes."
 trait_track_ac_potential_limit:0 "Limit"
 trait_track_ac_potential_talent:0 "Talent"
 trait_track_ac_potential_limit_desc:0 "An innate aptitude. Grades 1–3 are Mortal, 4–6 Earthly, and 7–9 Heavenly. Higher Limit delays each increase in Core formation cost."
 trait_track_ac_potential_talent_desc:0 "An innate aptitude. Grades 1–3 are Mortal, 4–6 Earthly, and 7–9 Heavenly. Higher Talent grants more lifestyle experience and monthly prestige."
'''
    custom = '# Generated by tools/build_potential.py.\n'
    for axis in ('limit', 'talent'):
        custom += f'AC_Potential{axis.title()} = {{ type = character\n'
        for level in range(9, 0, -1):
            custom += f'text = {{ trigger = {{ has_trait_xp = {{ trait = ac_potential track = ac_potential_{axis} value >= {THRESHOLDS[level-1]} }} }} localization_key = ac_potential_grade_{level} }}\n'
        custom += 'text = { localization_key = ac_potential_unrevealed }\n}\n'
    custom += 'AC_PotentialTalentBonus = { type = character\n'
    for level in range(9, 0, -1):
        custom += f'text = {{ trigger = {{ has_trait_xp = {{ trait = ac_potential track = ac_potential_talent value >= {THRESHOLDS[level-1]} }} }} localization_key = ac_potential_talent_bonus_{level} }}\n'
    custom += 'text = { localization_key = ac_potential_unrevealed }\n}\n'
    loc += ' ac_potential_unrevealed:0 "Unrevealed"\n'
    for level in range(1, 10):
        tier = ('Mortal','Earthly','Heavenly')[(level-1)//3]
        roman = ('I','II','III')[(level-1)%3]
        loc += f' ac_potential_grade_{level}:0 "{tier} {roman}"\n'
        loc += f' ac_potential_talent_bonus_{level}:0 "+{XP[level-1]*100:g}% lifestyle experience and +{PRESTIGE[level-1]:g} monthly prestige"\n'
    return {'common/traits/ac_potential_traits.txt': trait,
            'common/script_values/ac_potential_values.txt': values,
            'common/scripted_effects/ac_potential_effects.txt': effects,
            'common/on_action/ac_potential_on_actions.txt': hooks,
            'common/customizable_localization/ac_potential_custom_loc.txt': custom,
            'localization/english/ac_potential_l_english.yml': loc}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for relative, text in outputs().items():
        path = ROOT / 'AuraClash' / relative
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8-sig') != text:
                raise SystemExit(f'Stale generated file: {relative}')
        else:
            path.write_text(text, encoding='utf-8-sig')
    print('Verified Potential content.' if args.check else 'Built Potential content.')


if __name__ == '__main__':
    main()
