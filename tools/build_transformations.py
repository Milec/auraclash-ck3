"""Generate Aura Clash Transformation Techniques for CK3.

Follows the IF's <<transform>> widget and its ch8-9 awakenings:
- Seven Transformations, one per Martial Arts Style plus the Freestyle Limitbreaker:
  Akakiru "Reaper", Aoyusumu "Godhand", Kiihakai "Soul Domain", Kurokonton "Malocchio",
  Midorikatai "Titan" or "Asura", and Limitbreaker (any Style, or none).
- Each grants the IF's bonuses while transformed: Core points (+1 rating each in the Clash of
  Auras), Health (Vitality), Chi points and a special, plus an Aura Pressure boost
  (+500, or 250 + AP/8 at 2,000 AP and above):
  - Limitbreaker: every Core Surge +1, +1 Power, +1 Health, +10 AP from battle victories.
  - Reaper: +2 Power, +1 Agility, +1 Health; doubled bonuses from a bladed weapon.
  - Godhand: +1 Soul, Agility, Fortitude, Health and Chi; heals to full on transforming.
  - Soul Domain: +2 Soul, +1 Power, +2 Chi; every attack is Focused (+1 to every roll).
  - Malocchio: +2 Agility, +1 Fortitude, +1 Chi; copies the foe's Techniques (a victory
    teaches the first attack Technique the foe knows and the victor does not).
  - Titan: +2 Fortitude, +1 Power, +2 Health; always deals bonus damage (+1 on every hit).
  - Asura: +2 Power, +1 Fortitude, +1 Health; melee attacks are always Focused (+1 to
    Power Strike, Iron Guard and Flash Step).
- Transformations are trained, not only found: the MC awakens them by drawing a Heavenly
  Gate's power, but anyone may train one as a personal scheme (CK3's study schemes), alone
  or under a master who knows it. A Heavenly Gate gives the faster, riskier way (see
  tools/build_heavenly_gates.py).
- Requirements: the Immortal Core, 1,500 Aura Pressure, and the form's Style (Limitbreaker:
  every Combat Core at rating 3 or more).

Usage: python tools/build_transformations.py [--check]
"""
