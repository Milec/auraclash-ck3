def render():
    texts = {
        'common/traits/ac_transformation_traits.txt': traits(),
        'common/scripted_triggers/ac_transformation_triggers.txt': triggers(),
        'common/script_values/ac_transformation_values.txt': values(),
        'common/scripted_effects/ac_transformation_effects.txt': effects(),
        'common/schemes/scheme_types/ac_transformation_scheme.txt': scheme(),
        'common/character_interactions/ac_transformation_interactions.txt': interactions(),
        'common/on_action/ac_transformation_on_actions.txt': on_actions(),
        'events/ac_transformation_events.txt': events(),
        'localization/english/ac_transformation_l_english.yml': localization(),
    }
    return {k: (BOM + v.rstrip('\n') + '\n').encode('utf-8') for k, v in texts.items()}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = render()
    if args.check:
        stale = [r for r, d in files.items() if not (OUT / r).exists() or (OUT / r).read_bytes() != d]
        if stale:
            raise SystemExit('Stale generated files: ' + ', '.join(stale))
    else:
        for relative, data in files.items():
            path = OUT / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f'Transformations: {len(files)} files, {len(FORMS)} forms.')


if __name__ == '__main__':
    main()
