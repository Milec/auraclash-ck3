def knows_any():
    return 'OR = { ' + ' '.join(f'has_trait = ac_tf_{k}' for k in FORMS) + ' }'


def traits():
    out = ['# Generated by tools/build_transformations.py.']
    for key, (name, style, *_rest) in FORMS.items():
        icon = FORMS[key][7]
        out += [f'ac_tf_{key} = {{', f'\ticon = {icon}.dds', f'\tprowess = {TRAIT_PROWESS}',
                '\tmonthly_prestige = 0.25', '\tshown_in_ruler_designer = no', '\tinherit_chance = 0', '}', '']
    return '\n'.join(out)


def triggers():
    out = ['# Generated by tools/build_transformations.py. Character scope.',
           f'ac_knows_transformation_trigger = {{ {knows_any()} }}',
           'ac_transformation_ready_trigger = {', '\thas_trait = ac_cultivator', '\thas_trait = ac_immortal_core',
           f'\tac_aura_pressure_value >= {REQUIRED_AP}', '}']
    for key, (name, style, *_r) in FORMS.items():
        out += [f'ac_can_learn_tf_{key}_trigger = {{', '\tac_transformation_ready_trigger = yes', f'\tNOT = {{ has_trait = ac_tf_{key} }}']
        if style:
            out.append(f'\thas_trait = ac_style_{style}')
        else:
            out += [f'\tac_core_{c}_rating >= {LIMITBREAKER_CORE}' for c in CORES]
        if key == 'titan':
            out.append('\tNOT = { has_trait = ac_tf_asura }')
        if key == 'asura':
            out.append('\tNOT = { has_trait = ac_tf_titan }')
        out.append('}')
    out += ['ac_can_learn_any_transformation_trigger = {', '\tOR = {', *[f'\t\tac_can_learn_tf_{k}_trigger = yes' for k in FORMS], '\t}', '}',
            '# Can scope:actor learn a form this character knows?',
            'ac_can_teach_transformation_trigger = {', '\tOR = {',
            *[f'\t\tAND = {{ has_trait = ac_tf_{k} scope:actor = {{ ac_can_learn_tf_{k}_trigger = yes }} }}' for k in FORMS],
            '\t}', '}',
            '# Fighter scope, in a Clash of Auras.',
            'ac_duel_can_transform_trigger = {', '\tNOT = { has_variable = ac_duel_tf }', f'\t{knows_any()}', '\tac_chi_available >= 1', '}']
    return '\n'.join(out)


